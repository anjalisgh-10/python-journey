""" 
\n - New Line
\t - Tab Space
\\ - Backslash
\" - Double quotes
\' - Single quotes
"""

print("Hello World")
print("Hello\nWorld")
print("Hello\tWorld")

# Anjali\Singh
print("Anjali\\Singh")

# Anjali\\\Singh
print("Anjali\\\\\\Singh")

# My name is "Anjali" Singh
print("My name is 'Anjali' Singh")
print('My name is "Anjali" Singh')
print("My name is \"Anjali\" Singh")
